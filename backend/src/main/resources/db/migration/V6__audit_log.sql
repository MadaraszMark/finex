-- Admin audit napló

-- Az adminműveletek belső, visszakereshető nyoma (ki, mikor, honnan, mit csinált)
CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id    BIGINT        REFERENCES users (id),
    actor_email VARCHAR(255)  NOT NULL,
    action      VARCHAR(40)   NOT NULL,
    target_type VARCHAR(30)   NOT NULL,
    target_id   BIGINT,
    details     VARCHAR(1000),
    ip_address  VARCHAR(45),
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_audit_log_action CHECK (action IN (
        'USER_STATUS_CHANGED', 'USER_ROLE_CHANGED', 'ACCOUNT_STATUS_CHANGED', 'ACCOUNT_DEPOSIT', 'TRANSACTION_REVERSED',
        'CATEGORY_CREATED', 'CATEGORY_UPDATED', 'CATEGORY_DELETED', 'TICKET_STATUS_CHANGED', 'JOB_RUN')),
    CONSTRAINT ck_audit_log_target_type CHECK (target_type IN ('USER', 'ACCOUNT', 'TRANSACTION', 'CATEGORY', 'SUPPORT_TICKET', 'JOB'))
);

CREATE INDEX idx_audit_log_created ON audit_log (created_at DESC);
CREATE INDEX idx_audit_log_actor_created ON audit_log (actor_id, created_at DESC);

-- Csak bővíthető: közvetlen SQL-lel sem írható át vagy törölhető, így a nyomok nem tüntethetők el
CREATE FUNCTION forbid_audit_change() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'Az audit napló bejegyzése nem módosítható és nem törölhető (id: %)', OLD.id
        USING ERRCODE = 'integrity_constraint_violation';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_audit_log_immutable
    BEFORE UPDATE OR DELETE ON audit_log
    FOR EACH ROW EXECUTE FUNCTION forbid_audit_change();
